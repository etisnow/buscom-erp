/** Штрихкод той же расписки (Code128): номер 01211275323 внутри. */
const DELLIN_BARCODE = "0102919021610121127532326";

const CARRIERS = ["Деловые линии", "ПЭК", "КИТ (GTD)", "СДЭК", "Байкал Сервис"];

describe("parseWaybill — расписка «Деловых Линий»", () => {
  it("достаёт все поля доставки, номер — по штрихкоду", () => {
    expect(parseWaybill(DELLIN_OCR, [DELLIN_BARCODE], CARRIERS)).toEqual({
      carrier: "Деловые линии",
      trackingNumber: "26-01211275323",
      shippedAt: "2026-09-25",
      // Срок под «тип доставки Авто» — без подписи, первая дата после даты документа
      deliveryDate: "2026-09-29",
      weightGrams: 18_000,
      // OCR прочитал «0,32 м3» как «0:32 м3» — объём с бланка, а не произведение сторон
      volumeCm3: 320_000,
      lengthCm: 153,
      widthCm: 70,
      // Ошибка OCR — 0,3 м прочитано как 0,5; такое ловит только менеджер при проверке
      heightCm: 50,
      priceKopecks: 297_300,
      destination: "Тула",
    });
  });
});

describe("findTrackingNumber", () => {
  it("без штрихкода берёт прочитанное, если там одни цифры", () => {
    expect(findTrackingNumber("№26-01211275525", [])).toBe("26-01211275525");
  });

  it("мусор в номере без штрихкода не угадывает", () => {
    expect(findTrackingNumber("№26-012112755$25", [])).toBeNull();
  });

  it("путаницу O/0 и l/1 исправляет", () => {
    expect(findTrackingNumber("№ 26 - O12l1275323", [])).toBe("26-01211275323");
  });

  it("чужой штрихкод, не похожий на номер, не подставляет", () => {
    expect(findTrackingNumber("№26-01211275525", ["99999999999999"])).toBe("26-01211275525");
  });

  it("без знака номера — null", () => {
    expect(findTrackingNumber("расписка 26-01211275323", [DELLIN_BARCODE])).toBeNull();
  });
});

describe("findCarrier", () => {
  it("находит ТК по склеенному OCR названию", () => {
    expect(findCarrier("А ДЕЛОВЫЕЛИНИИ", CARRIERS)).toBe("Деловые линии");
  });

  it("короткие названия — только отдельным словом", () => {
    expect(findCarrier("Получатель Никитин", CARRIERS)).toBeNull();
    expect(findCarrier("Перевозчик: КИТ", CARRIERS)).toBe("КИТ (GTD)");
  });

  it("не из справочника не придумывает", () => {
    expect(findCarrier("Экспедиторская расписка", CARRIERS)).toBeNull();
  });
});

describe("отдельные поля", () => {
  it("дата документа — первая «от ДД.ММ.ГГГГ», не дата готовности", () => {
    expect(findDocumentDate("Е от 25.09.2026 г.\n29.09.2026 г.")).toBe("2026-09-25");
    expect(findDocumentDate("готово 29.09.2026")).toBeNull();
  });

  it("дата доставки по подписи — даже если она раньше даты документа в тексте", () => {
    expect(findDeliveryDate("Дата доставки: 02.10.2026\nНакладная от 25.09.2026")).toBe("2026-10-02");
    expect(findDeliveryDate("Плановая дата 30.09.2026")).toBe("2026-09-30");
  });

  it("дата доставки без подписи — первая после документа и не дальше двух месяцев", () => {
    expect(findDeliveryDate("от 25.09.2026 г.\nпаспорт выдан 01.02.2010\n29.09.2026 г.")).toBe("2026-09-29");
    expect(findDeliveryDate("от 25.09.2026 г.\nхранение до 25.12.2026")).toBeNull();
    expect(findDeliveryDate("от 25.09.2026 г. без других дат")).toBeNull();
    expect(findDeliveryDate("29.09.2026 без даты документа")).toBeNull();
  });

  it("несуществующую дату не берёт", () => {
    expect(findDeliveryDate("Дата доставки 31.02.2026")).toBeNull();
  });

  it("вес с запятой", () => {
    expect(findWeightGrams("мест: 2; 18,5 кг")).toBe(18_500);
    expect(findWeightGrams("без веса")).toBeNull();
  });

  it("габариты с разными знаками умножения, не объём в м3", () => {
    expect(findDimensionsCm("1,53 * 0,7 х 0,3 м")).toEqual([153, 70, 30]);
    expect(findDimensionsCm("1 x 2 x 3 м3")).toBeNull();
  });

  it("«Итог», а не «Итого»", () => {
    expect(findTotalKopecks("Итого 2191,00\nИтог 2973,00")).toBe(297_300);
    expect(findTotalKopecks("Итого 2191,00")).toBeNull();
  });

  it("город назначения из составного названия", () => {
    expect(findDestination("груза из г. Москва в г. Нижний Новгород (мест: 1")).toBe("Нижний Новгород");
  });
});

