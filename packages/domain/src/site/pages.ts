/** Страница для показа: сохранённая в базе поверх исходной. */
export function resolveSitePage(
  slug: SitePageSlug,
  saved: { title: string; metaTitle: string; metaDescription: string | null; body: string } | null,
): SitePageContent {
  const fallback = SITE_PAGE_DEFAULTS[slug];
  if (!saved) return fallback;
  return {
    slug,
    title: saved.title,
    metaTitle: saved.metaTitle,
    metaDescription: saved.metaDescription ?? "",
    body: saved.body,
  };
}
