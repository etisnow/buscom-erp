-- Транспортные компании становятся справочником и в карточке заказа: поле было
-- свободной строкой, теперь выбирается из списка (docs/DECISIONS.md).
--
-- Бэкфилл обязателен. В заказах, перенесённых из прежней ERP, встречаются
-- значения, которых в справочнике нет, и не единично: «Любая» (526 заказов),
-- «Другая» (200), GTD (95), «Энергия» (48), «Переоборудование» (38), «Ротэк» (1).
-- Без этой миграции первая же правка доставки такой заказ обнулила бы.
--
-- Часть из них — не перевозчики, а заглушки из прежней системы. Они заводятся
-- наравне с остальными: выключить лишнее администратор может в /admin/dictionaries,
-- а вот восстановить потерянное значение было бы неоткуда.
--
-- sortOrder 100 — ниже заведённых руками, чтобы список открывался с настоящих
-- компаний. ON CONFLICT: то, что уже есть в справочнике, не трогаем.

INSERT INTO "DictionaryItem" ("id", "type", "name", "sortOrder", "isActive", "updatedAt")
SELECT gen_random_uuid()::text, 'CARRIER', TRIM(o."carrier"), 100, true, CURRENT_TIMESTAMP
FROM (SELECT DISTINCT "carrier" FROM "Order" WHERE "carrier" IS NOT NULL AND TRIM("carrier") <> '') AS o
ON CONFLICT ("type", "name") DO NOTHING;
