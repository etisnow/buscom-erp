import {
  findCarrier,
  findDestination,
  findDimensionsCm,
  findDocumentDate,
  findTotalKopecks,
  findTrackingNumber,
  findWeightGrams,
  parseWaybill,
} from "@/domain/order/waybill-parse";

/**
 * Настоящий вывод Tesseract по скану экспедиторской расписки «Деловых Линий»
 * вместе с его ошибками: номер «…75525» вместо «…75323», высота 0,5 вместо 0,3.
 * Персональные данные (ФИО, телефоны, ИНН, паспорт) заменены выдуманными.
 */
